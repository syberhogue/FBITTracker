import { expect, test } from '@playwright/test';

test('manages funding, paper symbols, shared resources and persistent deletions', async ({ page, context }) => {
  test.setTimeout(120_000);
  page.setDefaultTimeout(15_000);
  await page.goto('/graduates');
  await page.getByRole('button', { name: 'Add MSc student' }).click();
  await page.getByLabel('Student name', { exact: true }).fill('Funding Student');
  await page.getByLabel('Student ID', { exact: true }).fill('FUND-1');
  await page.getByLabel('Supervisor account', { exact: true }).selectOption({ label: 'Dr. Alex Mercer' });
  await page.getByLabel('Start semester').selectOption('Fall');
  await page.getByLabel('Start year').fill('2024');
  await page.getByRole('button', { name: 'Save student', exact: true }).click();
  const funding = page.getByRole('region', { name: 'Funding', exact: true });
  await funding.getByRole('button', { name: 'Funding', exact: true }).click();
  await page.getByLabel('Grant / funding source').fill('Discovery grant');
  await page.getByLabel('Total amount (CAD)').fill('18000');
  await page.getByLabel('Funding duration').selectOption('3');
  await expect(page.getByRole('dialog')).toContainText('Aug 1, 2024');
  await expect(page.getByRole('dialog')).toContainText('Aug 31, 2025');
  await page.getByRole('button', { name: 'Save funding', exact: true }).click();
  const timeline = funding.getByRole('region', { name: 'Funding timeline', exact: true });
  const period = timeline.locator('button[data-task-key^="custom:"]');
  const form = timeline.locator('button[data-task-key^="funding-form:"]');
  await expect(period).toHaveAttribute('aria-label', /Aug 31, 2025/);
  await expect(form).toHaveAttribute('aria-label', /Aug 1, 2024/);
  await expect(timeline.getByRole('button', { name: 'Edit duration: GRA: Discovery grant' })).toBeVisible();
  await period.click();
  await page.getByRole('combobox', { name: 'Funding type', exact: true }).selectOption('RA');
  await page.getByLabel('Funding start semester').selectOption('Winter');
  await page.getByLabel('Funding start year').fill('2025');
  await page.getByLabel('Funding duration').selectOption('2');
  await page.getByRole('button', { name: 'Save funding', exact: true }).click();
  await expect(form).toHaveAttribute('aria-label', /Submit RA form: Discovery grant.*Dec 1, 2024/);
  await form.click();
  await page.getByLabel('Mark completed').check();
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(form).toHaveAttribute('aria-label', /Completed/);
  // Move a funding bar from its middle: preserve its two-semester length.
  const bar = timeline.getByRole('button', { name: 'Edit duration: RA: Discovery grant' });
  await bar.scrollIntoViewIfNeeded();
  const box = (await bar.boundingBox())!;
  const plot = (await timeline.locator('[data-timeline-plot]').boundingBox())!;
  const frame = timeline.locator('[data-zoomed]');
  const span = Number(await frame.getAttribute('data-visible-end')) - Number(await frame.getAttribute('data-visible-start'));
  const shift = (Date.parse('2025-12-31') - Date.parse('2025-08-31')) / span * plot.width * 0.8;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + shift, box.y + box.height / 2, { steps: 10 });
  expect(Math.abs((await timeline.locator('[data-timeline-plot]').boundingBox())!.y - plot.y)).toBeLessThan(1);
  await page.mouse.up();
  await expect(period).toHaveAttribute('aria-label', /Dec 31, 2025/);
  await expect(form).toHaveAttribute('aria-label', /Apr 1, 2025.*Completed/);
  await period.click();
  await expect(page.getByLabel('Funding start semester')).toHaveValue('Summer');
  await expect(page.getByLabel('Funding duration')).toHaveValue('2');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();

  await page.getByRole('button', { name: 'Category', exact: true }).click();
  await page.getByLabel('Category name').fill('Research outputs');
  await page.getByRole('button', { name: 'Save category', exact: true }).click();
  const papers = page.getByRole('region', { name: 'Research outputs', exact: true });
  await papers.getByRole('button', { name: 'Deadline', exact: true }).click();
  await page.getByLabel('Deadline name').fill('Journal submission');
  await page.getByLabel('Expected date', { exact: true }).fill('2026-02-01');
  await page.getByRole('button', { name: 'Save deadline', exact: true }).click();
  const paper = papers.locator('button[data-task-key^="custom:"]');
  await paper.click();
  await page.getByLabel('Item type / symbol').selectOption('Research Paper');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(paper).toHaveAttribute('data-item-type', 'Research Paper');
  await papers.getByRole('button', { name: /^Research outputs \d/ }).click();
  await papers.getByRole('button', { name: 'Edit deadline Journal submission', exact: true }).click();
  await expect(page.getByLabel('Item type / symbol')).toHaveValue('Research Paper');
  await page.getByLabel('Item type / symbol').selectOption('Report');
  await page.getByRole('button', { name: 'Save deadline', exact: true }).click();
  await expect(paper).toHaveAttribute('data-item-type', 'Report');
  await paper.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete deadline', exact: true }).click();
  await expect(paper).toHaveCount(0);
  const reports = page.getByRole('region', { name: 'Semester research progress reports timeline', exact: true });
  const report = reports.locator('button[data-task-key="report:2024-09-01"]');
  await report.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete deadline', exact: true }).click();
  await expect(report).toHaveCount(0);
  await page.getByRole('button', { name: 'Delete category Supervisory Committee', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Supervisory Committee', exact: true })).toHaveCount(0);

  // Navigate within the SPA: demo data deliberately resets on a full reload.
  await page.getByRole('link', { name: /Templates/ }).click();
  await page.getByRole('button', { name: 'Add resource', exact: true }).click();
  await page.getByLabel('Resource title').fill('Graduate forms');
  await page.getByLabel('Resource URL').fill('https://example.test/graduate-forms');
  await page.getByLabel('Resource description').fill('Forms for MSc students and supervisors.');
  await page.getByRole('button', { name: 'Save resource', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Graduate forms', exact: true })).toHaveAttribute('href', 'https://example.test/graduate-forms');
  await page.getByRole('link', { name: 'MSc student tracker', exact: true }).click();
  await page.getByRole('button', { name: /Funding Student/ }).click();
  await expect(report).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'Supervisory Committee', exact: true })).toHaveCount(0);
  const resources = page.getByRole('region', { name: 'MSc resources' });
  await expect(resources.getByRole('link', { name: 'Graduate forms', exact: true })).toBeVisible();
  await funding.screenshot({ path: 'test-results/msc-funding.png' });
  await context.addInitScript(() => { window.print = () => {}; });
  await page.getByRole('button', { name: 'Export', exact: true }).click();
  const opening = page.waitForEvent('popup');
  await page.getByRole('button', { name: 'PDF (Print / Save as PDF)', exact: true }).click();
  const pdf = await opening;
  await expect(pdf.getByRole('img', { name: /Overall student timeline/ })).toBeVisible();
  await pdf.pdf({ path: 'test-results/msc-funding.pdf', preferCSSPageSize: true });
  await pdf.close();
  await page.getByRole('button', { name: 'Done', exact: true }).click();
  await period.click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete deadline', exact: true }).click();
  await expect(period).toHaveCount(0);
  await expect(form).toHaveCount(0);
});
