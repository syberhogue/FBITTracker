import { expect, test } from '@playwright/test';

test('creates curriculum proposals, edits committee dates and preserves stage history', async ({ page }) => {
  test.setTimeout(90_000);
  page.setDefaultTimeout(15_000);
  await page.goto('/curriculum');
  await expect(page.getByRole('heading', { name: 'Curriculum Change Tracker', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add curriculum change' }).click();
  await page.getByLabel('Change title').fill('New analytics course');
  await page.getByLabel('Change template').selectOption('New Courses');
  await page.getByLabel('Planning start date').fill('2026-09-01');
  await page.getByLabel('Implementation academic year').fill('2027');
  await expect(page.getByRole('dialog')).toContainText('USC (Information)');
  await page.getByRole('button', { name: 'Save curriculum change', exact: true }).click();
  const uec = page.getByRole('region', { name: 'UEC · Faculty', exact: true });
  await expect(uec).toContainText('Sep 8, 2026');
  await uec.getByRole('button', { name: 'Update UEC (Approval)', exact: true }).click();
  await page.getByLabel('Outcome', { exact: true }).selectOption('approved');
  await page.getByLabel('Actual completion date').fill('2026-09-08');
  await page.getByLabel('Stage notes').fill('Approved after consultation');
  await page.getByRole('button', { name: 'Add link', exact: true }).click();
  await page.getByLabel('Link 3 title').fill('Course proposal');
  await page.getByLabel('Link 3 URL').fill('https://example.test/course-proposal');
  await page.getByRole('button', { name: 'Save stage', exact: true }).click();
  await expect(uec).toContainText('Approved after consultation');
  await expect(uec.getByRole('link', { name: 'Course proposal' })).toHaveAttribute('href', 'https://example.test/course-proposal');
  await page.getByRole('button', { name: 'Committee calendar', exact: true }).click();
  await page.getByLabel('Calendar committee').selectOption('FC');
  await page.getByLabel('FC meeting 2', { exact: true }).fill('2026-10-07');
  await page.getByRole('button', { name: 'Save committee calendar', exact: true }).click();
  await page.getByRole('button', { name: 'Reschedule pending stages', exact: true }).click();
  await expect(page.getByRole('region', { name: 'FC · Faculty', exact: true })).toContainText('Oct 7, 2026');
  await expect(uec).toContainText('Sep 8, 2026');
  await expect(uec).toContainText('Approved after consultation');
  const usc = page.getByRole('region', { name: 'USC · University', exact: true });
  await usc.getByRole('button', { name: 'Update USC (Information)', exact: true }).click();
  await expect(page.getByLabel('Stage purpose')).toHaveValue('Information');
  await expect(page.getByLabel('Outcome')).toContainText('Reported for information');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Add stage', exact: true }).click();
  await page.getByLabel('Stage title').fill('Cross-faculty consultation');
  await page.getByLabel('Meeting / stage deadline').fill('2026-10-16');
  await page.getByRole('button', { name: 'Save stage', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Update Cross-faculty consultation', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'MSc student tracker', exact: true }).click();
  await page.getByRole('link', { name: 'Curriculum Change Tracker', exact: true }).click();
  await expect(page.getByRole('region', { name: 'UEC · Faculty', exact: true })).toContainText('Approved after consultation');
  await page.locator('main').evaluate(element => element.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/curriculum-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('main').evaluate(element => element.scrollTo(0, 0));
  await expect(page.getByRole('heading', { name: 'Curriculum Change Tracker', exact: true })).toBeVisible();
  await page.screenshot({ path: 'test-results/curriculum-mobile.png', fullPage: true });
});

test('supports V2 and the ARC publication prerequisite for new programs', async ({ page }) => {
  await page.goto('/curriculum');
  await page.getByRole('button', { name: 'Add curriculum change' }).click();
  await page.getByLabel('Change title').fill('New specialization V2');
  await page.getByLabel('Change template').selectOption('New Specializations');
  await page.getByLabel('Approval process').selectOption('V2');
  await page.getByLabel('Planning start date').fill('2026-09-01');
  await page.getByRole('button', { name: 'Save curriculum change', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Curriculum change summary' })).toContainText('0/6 stages complete');
  await expect(page.getByRole('button', { name: 'Update UEC (Information)', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Update FC (Approval)', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add curriculum change' }).click();
  await page.getByLabel('Change title').fill('New undergraduate program');
  await page.getByLabel('Change template').selectOption('New Programs');
  await page.getByLabel('Planning start date').fill('2026-09-01');
  await page.getByRole('button', { name: 'Save curriculum change', exact: true }).click();
  await page.getByRole('button', { name: 'Update NOI made public', exact: true }).click();
  await page.getByLabel('Outcome').selectOption('reported');
  await page.getByLabel('Actual NOI publication date').fill('2026-09-20');
  await page.getByRole('button', { name: 'Save stage', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Record ARC approval');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Update ARC (Approval)', exact: true }).click();
  await page.getByLabel('Outcome').selectOption('approved');
  await page.getByLabel('Actual completion date').fill('2026-09-18');
  await page.getByRole('button', { name: 'Save stage', exact: true }).click();
  await page.getByRole('button', { name: 'Update NOI made public', exact: true }).click();
  await page.getByLabel('Outcome').selectOption('reported');
  await page.getByLabel('Actual NOI publication date').fill('2026-09-20');
  await page.getByRole('button', { name: 'Save stage', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Curriculum change summary' })).toContainText('Sep 20, 2028');
  await page.getByRole('button', { name: 'Reschedule pending stages', exact: true }).click();
  await expect(page.getByRole('region', { name: 'UEC · Faculty', exact: true })).toContainText('Oct 13, 2026');
});
