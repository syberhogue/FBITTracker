import { expect, test } from '@playwright/test';

test('settings generates a committee schedule and retains overrides, exclusions and other committees', async ({ page }) => {
  page.setDefaultTimeout(15_000);
  await page.goto('/settings');
  const settings = page.getByRole('region', { name: 'Committee meetings', exact: true });
  await settings.getByLabel('Calendar academic year').fill('2026');
  await settings.getByLabel('Meeting frequency').selectOption('monthly');
  await expect(settings.getByRole('heading', { name: 'UEC meetings (12)', exact: true })).toBeVisible();
  await expect(settings.getByLabel('UEC meeting 1', { exact: true })).toHaveValue('2026-09-08');
  await settings.getByLabel('Week of month').selectOption('-1');
  await settings.getByLabel('Meeting frequency').selectOption('quarterly');
  await expect(settings.getByRole('heading', { name: 'UEC meetings (4)', exact: true })).toBeVisible();
  await expect(settings.getByLabel('UEC meeting 2', { exact: true })).toHaveValue('2026-12-29');
  await settings.getByLabel('UEC meeting 1', { exact: true }).fill('2026-09-30');
  await settings.getByRole('button', { name: 'Delete UEC meeting 2', exact: true }).click();
  await settings.getByLabel('Calendar committee').selectOption('FC');
  await expect(settings.getByRole('heading', { name: 'FC meetings (12)', exact: true })).toBeVisible();
  await settings.getByLabel('Calendar academic year').fill('2027');
  await settings.getByLabel('Calendar academic year').fill('2026');
  await settings.getByLabel('Calendar committee').selectOption('UEC');
  await expect(settings.getByRole('heading', { name: 'UEC meetings (3)', exact: true })).toBeVisible();
  await expect(settings.getByLabel('UEC meeting 1', { exact: true })).toHaveValue('2026-09-30');
  await settings.getByRole('button', { name: 'Save committee calendar', exact: true }).click();
  await expect(settings.getByRole('status')).toContainText('Committee calendar saved');
  await settings.getByLabel('Agenda lead days 1', { exact: true }).fill('6');
  await settings.getByRole('button', { name: 'Save committee calendar', exact: true }).click();
  await expect(settings.getByRole('status')).toContainText('Committee calendar saved');
  await settings.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/committee-settings-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await settings.getByLabel('Meeting frequency').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/committee-settings-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('link', { name: 'Curriculum Change Tracker', exact: true }).click();
  await page.getByRole('button', { name: 'Committee calendar', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Committee calendar', exact: true });
  await expect(dialog.getByRole('heading', { name: 'UEC meetings (3)', exact: true })).toBeVisible();
  await expect(dialog.getByLabel('UEC meeting 1', { exact: true })).toHaveValue('2026-09-30');
  await expect(dialog.getByLabel('Agenda lead days 1', { exact: true })).toHaveValue('6');
  await expect(dialog.getByLabel('UEC meeting 2', { exact: true })).toHaveValue('2027-03-30');
  await dialog.getByLabel('Calendar committee').selectOption('FC');
  await expect(dialog.getByRole('heading', { name: 'FC meetings (12)', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Add curriculum change' }).click();
  await page.getByLabel('Change title').fill('Uses settings calendar');
  await page.getByLabel('Change template').selectOption('New Courses');
  await page.getByLabel('Planning start date').fill('2026-09-01');
  await page.getByRole('button', { name: 'Save curriculum change', exact: true }).click();
  await expect(page.getByRole('region', { name: 'UEC · Faculty', exact: true })).toContainText('Sep 30, 2026');
});

test('settings supports fixed-day schedules and rejects duplicated overrides', async ({ page }) => {
  await page.goto('/settings');
  const settings = page.getByRole('region', { name: 'Committee meetings', exact: true });
  await settings.getByLabel('Calendar academic year').fill('2026');
  await settings.getByLabel('Calendar committee').selectOption('ARC');
  await settings.getByLabel('Meeting frequency').selectOption('weekly');
  await settings.getByLabel('Day of week').selectOption('2');
  await settings.getByLabel('Schedule ends').fill('2026-12-31');
  await expect(settings.getByRole('heading', { name: 'ARC meetings (18)', exact: true })).toBeVisible();
  await settings.getByLabel('Meeting frequency').selectOption('fortnightly');
  await expect(settings.getByRole('heading', { name: 'ARC meetings (9)', exact: true })).toBeVisible();
  await settings.getByLabel('Meeting frequency').selectOption('monthly');
  await settings.getByLabel('Repeat pattern').selectOption('month-day');
  await settings.getByLabel('Day of month').fill('31');
  await expect(settings.getByLabel('ARC meeting 1', { exact: true })).toHaveValue('2026-09-30');
  await expect(settings.getByLabel('ARC meeting 2', { exact: true })).toHaveValue('2026-10-31');
  await settings.getByLabel('Meeting frequency').selectOption('yearly');
  await expect(settings.getByRole('heading', { name: 'ARC meetings (1)', exact: true })).toBeVisible();
  await settings.getByLabel('ARC meeting 1', { exact: true }).fill('');
  await expect(settings.getByLabel('ARC meeting 1', { exact: true })).toHaveValue('');
  await settings.getByLabel('ARC meeting 1', { exact: true }).fill('2026-10-30');
  await settings.getByRole('button', { name: 'Add meeting', exact: true }).click();
  await settings.getByLabel('ARC meeting 2', { exact: true }).fill('2026-10-30');
  await settings.getByRole('button', { name: 'Save committee calendar', exact: true }).click();
  await expect(settings.getByRole('alert')).toContainText('duplicate committee meeting dates');
  await settings.getByLabel('ARC meeting 2', { exact: true }).fill('2026-11-15');
  await settings.getByRole('button', { name: 'Save committee calendar', exact: true }).click();
  await expect(settings.getByRole('status')).toContainText('Committee calendar saved');
});
